#!/usr/bin/env node
/**
 * generate-token-contract.mjs
 *
 * Parses src/styles/tokens.contract.css and emits src/styles/tokens.contract.json
 * as the machine-readable source of truth for the token vocabulary.
 *
 * Consumed by:
 *   - tokens.contract.test.js  (parity assertions between light and dark)
 *   - Stylelint config          (allowed-list enforcement via declaration-property-value-allowed-list)
 *
 * Run:  node scripts/generate-token-contract.mjs
 *       npm run generate-tokens
 *       Automatically executed as "prebuild" before vite build.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

const CONTRACT_CSS = path.join(ROOT, 'src/styles/tokens.contract.css');
const CONTRACT_JSON = path.join(ROOT, 'src/styles/tokens.contract.json');

function extractTokenNames(cssText) {
  /** Match every --fs-* custom property declaration in the contract. */
  const pattern = /^\s*(--fs-[\w-]+)\s*:/gm;
  const names = [];
  let match;
  while ((match = pattern.exec(cssText)) !== null) {
    names.push(match[1]);
  }
  return names;
}

const cssText = fs.readFileSync(CONTRACT_CSS, 'utf8');
const tokens = extractTokenNames(cssText);

if (tokens.length === 0) {
  console.error('[generate-token-contract] ERROR: No tokens found in', CONTRACT_CSS);
  process.exit(1);
}

const output = {
  _comment:
    'Generated by scripts/generate-token-contract.mjs from tokens.contract.css. ' +
    'Do not edit manually — run `npm run generate-tokens` to regenerate.',
  tokens,
};

fs.writeFileSync(CONTRACT_JSON, JSON.stringify(output, null, 2) + '\n', 'utf8');
console.log(`[generate-token-contract] Wrote ${tokens.length} tokens to tokens.contract.json`);
